"""Build the standalone index.html from the Claude artifact page.

The artifact page (artifact/solution-delivery-queue.html) is the single source for the UI.
This script wraps it in a full HTML document and loads Supabase, config.js and
platform.js before the page's own script, so both versions stay identical.

Usage, from the repository root:
    python tools/build_app.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "artifact" / "solution-delivery-queue.html"
TARGET = ROOT / "index.html"
SUPABASE = "https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2.45.4/dist/umd/supabase.min.js"

HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<style>
:root{color-scheme:light;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}
body{margin:0}
img{max-width:100%}
[hidden]{display:none!important}
</style>
</head>
<body>
<!-- Generated by tools/build_app.py from artifact/solution-delivery-queue.html. Edit that file, then rebuild. -->
"""

RUNTIME = f"""<script src="{SUPABASE}"></script>
<script src="config.js"></script>
<script src="platform.js"></script>
"""


def main() -> None:
    page = SOURCE.read_text(encoding="utf-8")
    marker = "\n<script>\n"
    if page.count(marker) != 1:
        raise SystemExit("Expected exactly one inline <script> block in the artifact page.")
    body = page.replace(marker, "\n" + RUNTIME + "<script>\n", 1)
    TARGET.write_text(HEAD + body.rstrip("\n") + "\n</body>\n</html>\n", encoding="utf-8", newline="\n")
    print(f"Wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
